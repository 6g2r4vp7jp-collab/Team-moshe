#!/usr/bin/env python3
"""Build dashboard/data.js from the project's CSV files and the latest weekly report.

The dashboard is static (open dashboard/index.html, no server needed). Every value comes
from a file in the repo; sample rows/reports are flagged so the UI labels them.

Usage: python3 tools/build_dashboard.py [--today YYYY-MM-DD]
"""
import argparse
import csv
import datetime as dt
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORTS = ROOT / "analytics" / "reports"


def rows(rel):
    f = ROOT / rel
    if not f.exists():
        return []
    with f.open(encoding="utf-8-sig", newline="") as fh:
        return [dict(r) for r in csv.DictReader(fh)]


def d(s):
    try:
        return dt.date.fromisoformat((s or "").strip()[:10])
    except ValueError:
        return None


def latest_report():
    """Prefer the newest real report; fall back to the newest sample (flagged)."""
    files = sorted(REPORTS.glob("weekly_*.json"))
    real = [f for f in files if not f.stem.endswith("_SAMPLE")]
    pick = (real or files or [None])[-1]
    if not pick:
        return None
    rep = json.loads(pick.read_text(encoding="utf-8"))
    rep["file"] = str(pick.relative_to(ROOT))
    return rep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--today")
    a = ap.parse_args()
    today = dt.date.fromisoformat(a.today) if a.today else dt.date.today()
    horizon = today + dt.timedelta(days=7)

    cal = rows("marketing/content_calendar.csv")
    cal.sort(key=lambda r: r["date"])
    tasks = rows("marketing/tasks.csv")
    sponsors = rows("crm/sponsors.csv")
    promos = rows("crm/promotions.csv")
    leads = rows("crm/club_leads.csv")
    achievements = json.loads((ROOT / "brand" / "achievements.json").read_text(encoding="utf-8"))["achievements"]

    week_tasks = [t for t in tasks if t.get("status") != "done" and d(t.get("due")) and d(t["due"]) <= horizon]
    followups = []
    for kind, lst, name in (("ספונסר", sponsors, "company"), ("ארגון", promos, "organization"), ("מכון", leads, "name")):
        for r in lst:
            nf = d(r.get("next_followup"))
            if nf and nf <= horizon and r.get("status") not in ("won", "lost", "joined", "no_reply"):
                followups.append({"kind": kind, "name": r.get(name), "date": nf.isoformat(), "status": r.get("status"),
                                  "overdue": nf < today, "is_sample": r.get("is_sample") == "yes"})
    followups.sort(key=lambda x: x["date"])

    reel_ideas = [r for r in cal if r["format"] == "reel" and r["status"] in ("idea", "draft")]
    ready = [r for r in cal if r["status"] in ("ready", "approved")]
    out_dir = ROOT / "reels" / "out"
    rendered = sorted(str(p.relative_to(ROOT)) for p in out_dir.glob("*.mp4")) if out_dir.exists() else []

    lead_funnel = {}
    for r in leads:
        lead_funnel[r.get("status", "")] = lead_funnel.get(r.get("status", ""), 0) + 1

    try:
        rev = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    except OSError:
        rev = ""

    data = {
        "generated_at": dt.datetime.now().isoformat(timespec="minutes"), "today": today.isoformat(), "rev": rev,
        "calendar": cal, "week_calendar": [r for r in cal if today <= d(r["date"]) <= horizon],
        "reel_ideas": reel_ideas, "ready": ready, "rendered_files": rendered,
        "tasks": tasks, "week_tasks": week_tasks, "followups": followups,
        "sponsors": sponsors, "promotions": promos, "leads": leads, "lead_funnel": lead_funnel,
        "report": latest_report(),
        "verification": {"total": len(achievements), "verified": sum(1 for x in achievements if x.get("verified"))},
    }
    out = ROOT / "dashboard" / "data.js"
    out.write_text("// generated by tools/build_dashboard.py - do not edit by hand\nwindow.DASHBOARD_DATA = "
                   + json.dumps(data, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    rep = data["report"]
    print(f"wrote {out.relative_to(ROOT)}: {len(cal)} calendar rows, {len(week_tasks)} tasks this week, "
          f"{len(followups)} follow-ups, report={'none' if not rep else rep['file']}")
    if rep and rep.get("is_sample"):
        print("note: statistics come from SAMPLE data until real Insights are added to analytics/data/", file=sys.stderr)


if __name__ == "__main__":
    main()
