# Generates src/edit.generated.tsx from tools/edl.json: one TransitionSeries.Sequence per shot,
# captions placed on the shot's own clock (source time - shot in).
import json
S=json.load(open('tools/edl.json'))['shots']; FPS=30
def f(x): return round(x*FPS)
def q(s): return json.dumps(s,ensure_ascii=False)
out=[]; total=0
for i,s in enumerate(S):
    d=f(s['out'])-f(s['in']); total+=d
    body=[f'        <Shot name="{s["name"]}" trimBefore={{{f(s["in"])}}} zoom={{{s["z"]}}} origin={{{s["o"]}}} volume={{{0 if s.get("mute") else s.get("vol",1)}}} />']
    if 'label' in s:
        sub=f' sub={{{q(s["label"][1])}}}' if len(s['label'])>1 else ''
        body.append(f'        <Label text={{{q(s["label"][0])}}}{sub} />')
    for a,b,t in s.get('cap',[]):
        st=max(0,f(a)-f(s['in'])); du=min(d,f(b)-f(s['in']))-st
        body.append(f'        <Caption from={{{st}}} durationInFrames={{{du}}} text={{{q(t)}}} />')
    if 'title' in s: body.append(f'        <Title text={{{q(s["title"])}}} />')
    if 'cta' in s: body.append(f'        <Cta text={{{q(s["cta"])}}} />')
    out.append(f'      <TransitionSeries.Sequence name="{i:02d} {s["name"]}" durationInFrames={{{d}}}>\n'+"\n".join(body)+'\n      </TransitionSeries.Sequence>')
open('src/edit.generated.tsx','w').write('''// Generated by tools/gen.py from tools/edl.json - edit the EDL and re-run.
import { TransitionSeries } from "@remotion/transitions";
import { Caption, Cta, Label, Shot, Title } from "./parts";

export const TOTAL_FRAMES = %d;

export const Edit: React.FC = () => {
  return (
    <TransitionSeries name="Recipe shots">
%s
    </TransitionSeries>
  );
};
''' % (total,"\n".join(out)))
print('frames',total, total/FPS)
